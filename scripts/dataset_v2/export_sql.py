"""
Exports the candidate factor set + source manifest as idempotent SQL for the V12 registry tables.

    python -I scripts/dataset_v2/export_sql.py   # -> datasets/v2/build/registry_seed.<version>.sql

The dataset version is inserted with status 'draft'. Moving it to approved/active is a manual,
reviewed UPDATE (DATASET_V2_SCHEMA.md section 7), never part of this export.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pipeline  # noqa: E402

OUT = pipeline.BUILD / f"registry_seed.{pipeline.DATASET_VERSION}.sql"


def lit(v) -> str:
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "TRUE" if v else "FALSE"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return "ARRAY[" + ",".join(lit(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"


def main() -> int:
    manifest = pipeline.load_manifest()
    factors = json.loads((pipeline.BUILD / f"candidate_factors.{pipeline.DATASET_VERSION}.json").read_text(encoding="utf-8"))["factors"]
    lines = ["-- generated by scripts/dataset_v2/export_sql.py - do not edit", "BEGIN;"]
    for sid, s in manifest.items():
        lic = s.get("license", {})
        lines.append(
            "INSERT INTO factor_sources (source_id, publisher, title, url, publication_date, license_name, license_status, rag_allowed, "
            "verification_status, sha256, retrieved_on, manifest) VALUES ("
            + ", ".join([lit(sid), lit(s["publisher"]), lit(s["title"]), lit(s.get("fetch", {}).get("url") or s.get("landing_url")),
                         lit(s.get("publication_date")), lit(lic.get("name")), lit(lic.get("status", "unverified")),
                         lit(lic.get("status") == "verified" and lic.get("rag_allowed", True) is not False),
                         lit(s["verification_status"]), lit(s.get("fetch", {}).get("sha256")), lit(s.get("retrieved")),
                         lit(json.dumps(s, ensure_ascii=False)) + "::jsonb"])
            + ") ON CONFLICT (source_id) DO NOTHING;")
    lines.append(f"INSERT INTO factor_dataset_versions (version, status, notes) VALUES ({lit(pipeline.DATASET_VERSION)}, 'draft', "
                 "'Generated candidate set; requires human scientific review before approval') ON CONFLICT DO NOTHING;")
    for f in factors:
        cols = ["factor_id", "dataset_version", "record_kind", "value", "unit", "region", "applies_to_regions", "proxy_regions",
                "applicable_year", "scope", "system_boundary", "gases", "statistic", "source_id", "citation_of_record",
                "source_locator", "verification_status", "scientific_status", "uncertainty_level", "uncertainty_notes",
                "superseded_by", "notes"]
        row = dict(f, uncertainty_level=f["uncertainty"]["level"], uncertainty_notes=f["uncertainty"]["notes"])
        lines.append(f"INSERT INTO factor_records ({', '.join(cols)}) VALUES ({', '.join(lit(row.get(c)) for c in cols)}) "
                     "ON CONFLICT (factor_id, dataset_version) DO NOTHING;")
    # activity -> factor map (reviewed CSV) + food-by-weight rows from GLOBAL proxies usable for IN
    import csv
    ids = {f["factor_id"]: f for f in factors}
    map_rows = list(csv.DictReader((pipeline.V2 / "reviewed" / "activity_factor_map.v1.csv").open(encoding="utf-8", newline="")))
    for f in factors:
        if f["factor_id"].startswith("food.global.") and "IN" in f["proxy_regions"]:
            map_rows.append({"activity_key": "food:" + f["factor_id"].split(".", 2)[2], "region": "IN", "variant": "default",
                             "factor_id": f["factor_id"], "status": "provisional", "quantity_unit": "kg", "occupancy_rule": "",
                             "accounting_rule": "global_proxy", "missing_information": ""})
    for r in map_rows:
        if r["factor_id"] and r["factor_id"] not in ids:
            raise SystemExit(f"activity map references unknown factor {r['factor_id']}")
        lines.append(
            "INSERT INTO activity_factor_map (dataset_version, activity_key, region, variant, factor_id, status, quantity_unit, "
            "occupancy_rule, accounting_rule, missing_information) VALUES ("
            + ", ".join(lit(x) for x in [pipeline.DATASET_VERSION, r["activity_key"], r["region"], r["variant"], r["factor_id"] or None,
                                         r["status"], r["quantity_unit"], r["occupancy_rule"] or None, r["accounting_rule"] or None,
                                         r["missing_information"] or None])
            + ") ON CONFLICT (dataset_version, activity_key, region, variant) DO NOTHING;")
    lines.append("COMMIT;")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(manifest)} sources + {len(factors)} factors -> {OUT.relative_to(pipeline.REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
