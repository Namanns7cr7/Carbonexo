"""
Indexes the OKF bundle into the V14 scientific corpus (sci_corpus_versions / sci_documents / sci_chunks).

    python -I scripts/dataset_v2/okf_index.py [--embed] [--activate] [--location asia-south1]
        -> datasets/v2/build/sci_corpus.<corpus_version>.sql   (apply with psql; nothing is written to a DB here)

Chunks come from okf_consumer (section chunks, provenance metadata, numeric masking, injection
sanitising). --embed calls Vertex AI text-embedding-005 (RETRIEVAL_DOCUMENT, 768 dims) with your
gcloud credentials; without it the chunks are lexical-only (embedding NULL). The corpus is written as
'validated'; --activate also makes it the active corpus (staging/local only - production activation is
a reviewed, manual step).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
import sys
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import okf_consumer as oc  # noqa: E402
import pipeline  # noqa: E402
from export_sql import lit  # noqa: E402

BUNDLE = pipeline.REPO / "datasets/v2/okf/bundle/ecomind"
EMBED_MODEL = "text-embedding-005"


def embed(texts: list[str], location: str) -> list[list[float]]:
    gcloud = "gcloud.cmd" if sys.platform == "win32" else "gcloud"
    token = subprocess.run([gcloud, "auth", "print-access-token"], capture_output=True, text=True, check=True).stdout.strip()
    url = (f"https://{location}-aiplatform.googleapis.com/v1/projects/carbonexo/locations/{location}"
           f"/publishers/google/models/{EMBED_MODEL}:predict")
    out = []
    for i in range(0, len(texts), 5):
        body = {"instances": [{"content": t, "task_type": "RETRIEVAL_DOCUMENT"} for t in texts[i:i + 5]]}
        req = urllib.request.Request(url, data=json.dumps(body).encode(), method="POST",
                                     headers={"Authorization": f"Bearer {token}", "Content-Type": "application/json"})
        with urllib.request.urlopen(req, timeout=120) as r:
            out += [p["embeddings"]["values"] for p in json.loads(r.read())["predictions"]]
    return out


def build(do_embed: bool, activate: bool, location: str) -> tuple[Path, dict]:
    now = datetime.now(timezone.utc)
    b = oc.Bundle(BUNDLE, now)
    digest = b.version["bundle_digest"]
    corpus = f"okf-pilot.v1-{digest[:12]}"
    manifest = set(pipeline.load_manifest())
    chunks = [c for c in b.chunks if c.text.strip()]
    texts = [f"{c.meta['title']}. {c.heading}. {c.text}" for c in chunks]
    vectors = embed(texts, location) if do_embed else [None] * len(chunks)
    lines = ["-- generated by scripts/dataset_v2/okf_index.py - do not edit", "BEGIN;",
             f"INSERT INTO sci_corpus_versions (corpus_version, embedding_model, dimensions, chunking, status) VALUES ({lit(corpus)}, "
             f"{lit(EMBED_MODEL if do_embed else 'none')}, 768, {lit(json.dumps({'strategy': 'okf-section', 'bundle_digest': digest}))}::jsonb, "
             "'validated') ON CONFLICT (corpus_version) DO NOTHING;"]
    docs = {}
    for cid, c in b.concepts.items():
        fm = c["fm"]
        cx = fm.get("carbonexo") or {}
        sid = cx.get("source_id") if fm.get("type") == "Scientific Source" else (fm.get("sources") or [{}])[0].get("id")
        sid = sid if sid in manifest else None
        region = cx.get("region") or "ANY"
        doc_id = hashlib.md5(f"{corpus}:{cid}".encode()).hexdigest()
        doc_uuid = f"{doc_id[:8]}-{doc_id[8:12]}-{doc_id[12:16]}-{doc_id[16:20]}-{doc_id[20:32]}"
        docs[cid] = doc_uuid
        sha = pipeline.sha256(BUNDLE / c["path"])
        lines.append("INSERT INTO sci_documents (id, corpus_version, source_id, okf_concept_id, bundle_digest, title, gcs_uri, sha256, region) "
                     f"VALUES ({lit(doc_uuid)}, {lit(corpus)}, {lit(sid)}, {lit(cid)}, {lit(digest)}, {lit(fm.get('title', cid))}, "
                     f"{lit('okf://ecomind/' + c['path'])}, {lit(sha)}, {lit(region)}) ON CONFLICT DO NOTHING;")
    idx = {}
    for c, vec in zip(chunks, vectors):
        i = idx.get(c.concept_id, 0)
        idx[c.concept_id] = i + 1
        fm = b.concepts[c.concept_id]["fm"]
        region = c.meta.get("region") or "ANY"
        sid = next((ci["id"] for ci in c.citations if ci["id"] in manifest), None)
        content = c.text
        stale = fm.get("stale_after")
        lines.append(
            "INSERT INTO sci_chunks (document_id, corpus_version, source_id, okf_concept_id, okf_type, role, okf_status, trust_tier, "
            "stale_after, generated_at, citations, registry_pointer, injection_flags, chunk_index, locator, heading_path, content, "
            "content_sha256, token_count, region, embedding, embedding_model) VALUES ("
            + ", ".join([lit(docs[c.concept_id]), lit(corpus), lit(sid), lit(c.concept_id), lit(c.meta["type"]), lit(c.meta["role"]),
                         lit(c.meta["status"]), lit(c.meta["trust_tier"]), lit(stale) + ("::timestamptz" if stale else ""),
                         lit(c.meta.get("generated_at")) + ("::timestamptz" if c.meta.get("generated_at") else ""),
                         lit(json.dumps(c.citations, ensure_ascii=False)) + "::jsonb", lit(c.meta.get("factor_id")),
                         lit(json.dumps(c.injection_flags)) + "::jsonb", str(i), lit(f"{c.concept_id} § {c.heading}"),
                         lit(f"{c.meta['title']} › {c.heading}"), lit(content), lit(hashlib.sha256(content.encode()).hexdigest()),
                         str(max(1, len(content.split()))), lit(region),
                         (lit("[" + ",".join(f"{x:.7f}" for x in vec) + "]") + "::vector") if vec else "NULL",
                         lit(EMBED_MODEL) if vec else "NULL"])
            + ") ON CONFLICT DO NOTHING;")
    if activate:
        lines.append("UPDATE sci_corpus_versions SET status = 'retired' WHERE status = 'active';")
        lines.append(f"UPDATE sci_corpus_versions SET status = 'active' WHERE corpus_version = {lit(corpus)};")
    lines.append("COMMIT;")
    out = pipeline.BUILD / f"sci_corpus.{corpus}.sql"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out, {"corpus_version": corpus, "documents": len(docs), "chunks": len(chunks), "embedded": do_embed,
                 "bundle_digest": digest, "activated": activate}


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--embed", action="store_true")
    ap.add_argument("--activate", action="store_true")
    ap.add_argument("--location", default="asia-south1")
    a = ap.parse_args(argv)
    out, info = build(a.embed, a.activate, a.location)
    print(json.dumps(info), "->", out.relative_to(pipeline.REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
