/**
 * After every coach answer: the three ways to act on it, pointed at this
 * week's biggest logged source. Advice that can't be acted on is just text.
 */
function NextSteps({ category }: { category: Category | null }) {
  const cat = category ? CATEGORY_META[category].label.toLowerCase() : null;
  const link = 'inline-flex items-center gap-1 rounded-full border border-border bg-surface px-2.5 py-1 text-[11px] font-bold text-text transition-colors hover:border-lime hover:text-lime-deep';
  return (
    <nav aria-label="Act on this" className="mt-3 flex flex-wrap gap-1.5 border-t border-border/40 pt-2.5">
      <Link href={category ? `/app/track?cat=${category}` : '/app/track'} className={link}>
        <Plus className="h-3 w-3" /> Log {cat ?? 'an activity'}
      </Link>
      <Link href="/app/actions" className={link}>
        <ListChecks className="h-3 w-3" /> Plan a {cat ? `${cat} ` : ''}swap
      </Link>
      <Link href="/app/simulate" className={link}>
        <FlaskConical className="h-3 w-3" /> Try it in Carbon Twin
      </Link>
    </nav>
  );
}
